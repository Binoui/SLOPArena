#!/usr/bin/env python3
"""Check or regenerate discovery adapters from skills/ (stdlib only)."""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = "<!-- Generated by tools/sync_agent_skills.py; edit skills/ instead. -->"
IGNORE_START = "# BEGIN project skill adapters (tools/sync_agent_skills.py)"
IGNORE_END = "# END project skill adapters"


def expected_files(root: Path) -> dict[Path, str]:
    expected: dict[Path, str] = {}
    names: list[str] = []
    for source in sorted((root / "skills").glob("*/SKILL.md")):
        name = source.parent.name
        text = source.read_text(encoding="utf-8")
        match = re.match(r"\A---\n(.*?)\n---(?:\n|$)", text, re.DOTALL)
        if not match:
            raise ValueError(f"{source.relative_to(root)}: missing skill frontmatter")
        front = match.group(1)
        declared = re.search(r"(?m)^name: ([a-z0-9-]+)$", front)
        description = re.search(r"(?m)^description: (.+)$", front)
        if (not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name)
                or len(name) > 64 or not declared or declared.group(1) != name):
            raise ValueError(f"{source.relative_to(root)}: name must match its directory")
        if not description or description.group(1).strip() in {'""', "''"}:
            raise ValueError(f"{source.relative_to(root)}: missing description")
        names.append(name)
        policy = source.parent / "agents/openai.yaml"
        policy_text = policy.read_text(encoding="utf-8") if policy.is_file() else None
        explicit = bool(policy_text and re.search(
            r"(?m)^\s+allow_implicit_invocation:\s*false\s*$", policy_text))
        for harness in (".agents", ".omp"):
            prefix = Path(harness) / "skills" / name
            header = front + ("\ndisable-model-invocation: true" if explicit and harness == ".omp" else "")
            expected[prefix / "SKILL.md"] = (
                f"---\n{header}\n---\n\n{MARKER}\n\n"
                f"Read the selected checkout's [AGENTS.md](../../../AGENTS.md), then "
                f"read and follow the maintained [{name} workflow](../../../skills/{name}/SKILL.md). "
                "Resolve that workflow's sibling references from its source directory. "
                "Run project commands from the selected SLOPArena checkout. "
                "Loading a skill does not grant commit, push, install, or publication permission.\n"
            )
            if policy_text and harness == ".agents":
                expected[prefix / "agents/openai.yaml"] = policy_text
    if not names:
        raise ValueError("No canonical skills found in skills/")
    lines = [IGNORE_START, "/.agents/*", "!/.agents/skills/", "/.agents/skills/*"]
    lines += [f"!/.agents/skills/{name}/" for name in names]
    lines += ["/.agents/skills/*/*", "!/.agents/skills/*/SKILL.md",
              "!/.agents/skills/*/agents/", "/.agents/skills/*/agents/*",
              "!/.agents/skills/*/agents/openai.yaml", IGNORE_END]
    block = "\n".join(lines)
    ignore_path = root / ".gitignore"
    ignore = ignore_path.read_text(encoding="utf-8") if ignore_path.exists() else ""
    if IGNORE_START in ignore or IGNORE_END in ignore:
        if ignore.count(IGNORE_START) != 1 or ignore.count(IGNORE_END) != 1:
            raise ValueError("Malformed project skill adapter block in .gitignore")
        before, rest = ignore.split(IGNORE_START, 1)
        _, after = rest.split(IGNORE_END, 1)
        ignore = before + block + after
    else:
        ignore = ignore.rstrip() + "\n\n" + block + "\n"
    expected[Path(".gitignore")] = ignore
    return expected


def sync(root: Path, write: bool = False) -> list[str]:
    expected = expected_files(root)
    drift: list[str] = []
    updates: list[tuple[Path, str]] = []
    for path, content in expected.items():
        target = root / path
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == content:
            continue
        drift.append(str(path))
        if write:
            if path.name == "SKILL.md" and current is not None and MARKER not in current:
                raise ValueError(f"Refusing to overwrite an unmanaged adapter: {path}")
            updates.append((target, content))
    # Validate every destination before making any writes.
    for target, content in updates:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    for harness in (".agents", ".omp"):
        for target in sorted((root / harness / "skills").glob("*/SKILL.md")):
            path = target.relative_to(root)
            if MARKER not in target.read_text(encoding="utf-8"):
                continue
            if path in expected:
                policy = target.parent / "agents/openai.yaml"
                if harness == ".agents" and policy.is_file() and policy.relative_to(root) not in expected:
                    drift.append(f"obsolete: {policy.relative_to(root)}")
                    if write:
                        policy.unlink()
                continue
            drift.append(f"obsolete: {path}")
            if write:
                target.unlink()
                policy = target.parent / "agents/openai.yaml"
                if policy.is_file():
                    policy.unlink()
    return drift


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate owned adapters")
    mode.add_argument("--check", action="store_true", help="check only (the default)")
    args = parser.parse_args()
    try:
        drift = sync(ROOT, args.write)
    except (OSError, ValueError) as error:
        print(f"Skill adapter check failed: {error}")
        return 1
    if drift and not args.write:
        print("Skill adapters are stale; run python3 tools/sync_agent_skills.py --write:")
        print("\n".join(f"- {path}" for path in drift))
        return 1
    print(f"Skill adapters {'updated' if args.write else 'checked'} ({len(drift)} changes).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
