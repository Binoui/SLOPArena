ADVANCE = 5.6  # glyph width 4 + spacing


def text_strokes(text, height, origin=(0.0, 0.0), align="center", tracking=1.0):
    """Polylines for `text` scaled to cap `height`, as 2D points (u right, v up).

    Returns (strokes, width). align: left/center/right relative to origin.
    """
    s = height / 6.0
    advance = ADVANCE * tracking
    width = (len(text) * advance - (advance - 4)) * s if text else 0.0
    if align == "center":
        u0 = origin[0] - width / 2
    elif align == "right":
        u0 = origin[0] - width
    else:
        u0 = origin[0]
    strokes = []
    for i, ch in enumerate(text):
        glyph = GLYPHS.get(ch.upper() if ch.upper() in GLYPHS else ch)
        if not glyph:
            continue
        gx = u0 + i * advance * s
        for line in glyph:
            strokes.append([(gx + x * s, origin[1] + y * s) for x, y in line])
    return strokes, width


def vertical_text_strokes(text, height, origin=(0.0, 0.0), spacing=1.25):
    """Letters stacked top-to-bottom (classic blade sign). origin = top centre."""
    s = height / 6.0
    strokes = []
    for i, ch in enumerate(text):
        glyph = GLYPHS.get(ch.upper() if ch.upper() in GLYPHS else ch)
        if not glyph:
            continue
        top = origin[1] - i * height * spacing
        for line in glyph:
            strokes.append([(origin[0] + (x - 2) * s, top - (6 - y) * s) for x, y in line])
    return strokes, len(text) * height * spacing
