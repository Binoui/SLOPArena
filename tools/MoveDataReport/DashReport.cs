using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using SlopArena.Shared;

namespace SlopArena.MoveDataReport;

/// <summary>
/// Homing dash frame data (ADR-0042) measured in the real shared sim: how long the dash takes,
/// how long the defender has before the follow-up lands, and how each normal links on arrival.
/// Usage: dotnet run --project tools/MoveDataReport -- --dash [character|all] [--out path]
/// </summary>
internal static class DashReport
{
    private const ulong Attacker = 1, Defender = 100;
    private const float StartX = 50f, StartZ = 50f;
    private static readonly float[] GroundDistances = { 3f, 6f, 9f, 12f, 15f, 18f };
    private static readonly float[] AirDistances = { 6f, 9f, 12f };
    private static readonly float[] SidestepDistances = { 4f, 8f, 12f };
    private static readonly float[] ApexDistances = { 4f, 7f, 10f };
    private static readonly string[] Roster = { "fightguy", "wibou", "manki", "bonk", "bashie", "salamander" };
    private static readonly (string Label, byte Wire)[] Normals =
        { ("1", AbilitySlots.Slot1), ("2", AbilitySlots.Slot3), ("3", AbilitySlots.Slot4) };

    internal static int Run(string[] args)
    {
        string which = args.FirstOrDefault(a => !a.StartsWith("--")) ?? "all";
        string? outPath = Program.ParseArg(args, "--out");
        var names = which == "all" ? Roster : new[] { which.ToLowerInvariant() };
        var sb = new StringBuilder();
        sb.AppendLine("# Homing dash frame data");
        sb.AppendLine();
        sb.AppendLine($"> Generated by `tools/MoveDataReport --dash` ({DateTime.UtcNow:yyyy-MM-dd HH:mm} UTC) from the real shared sim, mirror matches on flat ground. 60 ticks = 1 s.");
        sb.AppendLine();
        sb.AppendLine($"Config: float {HomingDashConfig.FloatTicks} t, speed {HomingDashConfig.Speed} m/s for up to {HomingDashConfig.MaxTravelTicks} t " +
            $"({HomingDashConfig.Speed * HomingDashConfig.MaxTravelTicks / 60f:0.#} m), arrival gap {HomingDashConfig.ArrivalGap} m, " +
            $"arrival window {HomingDashConfig.ArriveWindowTicks} t, air hover {HomingDashConfig.ArriveHoverTicks} t, " +
            $"miss lock {HomingDashConfig.MissRecoveryTicks} t, cooldown {HomingDashConfig.CooldownTicks} t.");
        sb.AppendLine();
        sb.AppendLine("Columns: **arrive** = press → arrival tick. **hit N** = press → first contact when normal N is pressed on the first arrival tick (`-` = whiffs from there). " +
            "**react** = ticks the defender sees the dash before the fastest normal lands. **free** = press → actionable with no follow-up.");
        foreach (string name in names)
            AppendFighter(sb, name, Resolve(name));
        string text = sb.ToString();
        if (outPath != null)
        {
            string? dir = Path.GetDirectoryName(outPath);
            if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
            File.WriteAllText(outPath, text);
            Console.Error.WriteLine($"wrote {outPath}");
        }
        else Console.Write(text);
        return 0;
    }

    private static MatchContentEntry Resolve(string name) => name switch
    {
        "bashie" => BuiltInContentResolver.Resolve(CharacterClass.Bashie),
        "salamander" => BuiltInContentResolver.Resolve(CharacterClass.Salamander),
        _ => Program.ResolveEntry(name),
    };

    private static void AppendFighter(StringBuilder sb, string name, MatchContentEntry entry)
    {
        var def = entry.Definition;
        sb.AppendLine();
        sb.AppendLine($"## {def.DisplayName}");
        sb.AppendLine();
        sb.AppendLine("Grounded target, standing still:");
        sb.AppendLine();
        sb.AppendLine("| distance | arrive | hit 1 | hit 2 | hit 3 | react | free |");
        sb.AppendLine("|---:|---:|---:|---:|---:|---:|---:|");
        foreach (float d in GroundDistances)
        {
            var dash = Measure(entry, d, TargetMove.Stand, 0);
            var hits = Normals.Select(n => Measure(entry, d, TargetMove.Stand, n.Wire).FirstContact).ToArray();
            int fastest = hits.Where(h => h >= 0).DefaultIfEmpty(-1).Min();
            sb.AppendLine($"| {d:0} m | {Ticks(dash.Arrive, dash.Miss)} | {Hit(hits[0])} | {Hit(hits[1])} | {Hit(hits[2])} | " +
                $"{(fastest >= 0 ? fastest.ToString() : "-")} | {dash.Actionable} |");
        }

        float arrival = def.CapsuleRadius * 2f + HomingDashConfig.ArrivalGap;
        var control = Normals.Select(n => StandingHit(entry, arrival, n.Wire)).ToArray();
        sb.AppendLine();
        sb.AppendLine($"Control, no dash: each normal pressed from standstill at the arrival spacing ({arrival:0.00} m between centres): " +
            string.Join(", ", Normals.Select((n, i) => $"{n.Label} {(control[i] >= 0 ? $"hits on tick {control[i]}" : "whiffs")}")) + ".");

        sb.AppendLine();
        sb.AppendLine("Target jumps on the dash press (full hop); aerial pressed on arrival. **drop** = metres the attacker falls from arrival to contact:");
        sb.AppendLine();
        sb.AppendLine("| distance | arrive | height | air 1 | air 2 | air 3 | drop (fastest) |");
        sb.AppendLine("|---:|---:|---:|---:|---:|---:|---:|");
        foreach (float d in AirDistances)
        {
            var dash = Measure(entry, d, TargetMove.Jump, 0);
            var aerials = Normals.Select(n => Measure(entry, d, TargetMove.Jump, n.Wire)).ToArray();
            var best = aerials.Where(a => a.FirstContact >= 0).OrderBy(a => a.FirstContact).FirstOrDefault();
            sb.AppendLine($"| {d:0} m | {Ticks(dash.Arrive, dash.Miss)} | {dash.ArrivalHeight:0.0} m | {Hit(aerials[0].FirstContact)} | " +
                $"{Hit(aerials[1].FirstContact)} | {Hit(aerials[2].FirstContact)} | {(best == null ? "-" : $"{best.DropToContact:0.00} m")} |");
        }

        sb.AppendLine();
        sb.AppendLine($"Attacker jumps, dashes {JumpLead} t later; aerial pressed on arrival. Ticks count from the dash press:");
        sb.AppendLine();
        sb.AppendLine("| target | distance | arrive | height | air 1 | air 2 | air 3 | drop (fastest) |");
        sb.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|");
        foreach (var (label, move) in new[] { ("standing", TargetMove.Stand), ("jumping", TargetMove.Jump) })
        foreach (float d in AirDistances)
        {
            var dash = Measure(entry, d, move, 0, attackerJumps: true);
            var aerials = Normals.Select(n => Measure(entry, d, move, n.Wire, attackerJumps: true)).ToArray();
            var best = aerials.Where(a => a.FirstContact >= 0).OrderBy(a => a.FirstContact).FirstOrDefault();
            sb.AppendLine($"| {label} | {d:0} m | {Ticks(dash.Arrive, dash.Miss)} | {dash.ArrivalHeight:0.0} m | {Hit(aerials[0].FirstContact)} | " +
                $"{Hit(aerials[1].FirstContact)} | {Hit(aerials[2].FirstContact)} | {(best == null ? "-" : $"{best.DropToContact:0.00} m")} |");
        }

        sb.AppendLine();
        sb.AppendLine("Attacker full-jumps and dashes at the apex; aerial pressed mid-dash (4 t into the travel) / on arrival. " +
            "**dy** = attacker height above the target on arrival:");
        sb.AppendLine();
        sb.AppendLine("| target | distance | arrive | dy | air 1 | air 2 | air 3 |");
        sb.AppendLine("|---|---:|---:|---:|---:|---:|---:|");
        foreach (var (label, move, high) in new[] { ("standing", TargetMove.Stand, false), ("standing, double jump", TargetMove.Stand, true),
                     ("jumping", TargetMove.Jump, false) })
        foreach (float d in ApexDistances)
        {
            var dash = Measure(entry, d, move, 0, attackerJumps: true, apex: true, doubleJump: high);
            string Cell(byte wire)
            {
                var mid = Measure(entry, d, move, wire, attackerJumps: true, apex: true, midDash: true, doubleJump: high).FirstContact;
                var late = Measure(entry, d, move, wire, attackerJumps: true, apex: true, doubleJump: high).FirstContact;
                return $"{Hit(mid)} / {Hit(late)}";
            }
            sb.AppendLine($"| {label} | {d:0} m | {Ticks(dash.Arrive, dash.Miss)} | {dash.ArrivalDy:0.0} m | " +
                $"{Cell(Normals[0].Wire)} | {Cell(Normals[1].Wire)} | {Cell(Normals[2].Wire)} |");
        }

        sb.AppendLine();
        sb.AppendLine("Target runs sideways from the press (does the 4°/tick turn still catch it?):");
        sb.AppendLine();
        sb.AppendLine("| distance | result | free |");
        sb.AppendLine("|---:|---|---:|");
        foreach (float d in SidestepDistances)
        {
            var dash = Measure(entry, d, TargetMove.Sidestep, 0);
            sb.AppendLine($"| {d:0} m | {(dash.Arrive >= 0 ? $"arrives at {dash.Arrive}" : $"misses at {dash.Miss}")} | {dash.Actionable} |");
        }

        var miss = Measure(entry, 19.5f, TargetMove.Stand, 0);
        sb.AppendLine();
        sb.AppendLine($"Out of range (19.5 m): {Ticks(miss.Arrive, miss.Miss)}, actionable at {miss.Actionable} (the defender's punish window after the miss is {miss.Actionable - Math.Max(miss.Miss, 0)} t).");
    }

    private enum TargetMove { Stand, Jump, Sidestep }

    private sealed record DashRun(int Arrive, int Miss, int Actionable, int FirstContact, float ArrivalHeight, float DropToContact, float ArrivalDy);

    /// <summary>Press the dash on tick 0; optionally press <paramref name="followUp"/> on the first arrival tick.</summary>
    private const int JumpLead = 10;

    /// <summary>Mid-dash presses land this many ticks into the travel, after the float.</summary>
    private const int MidDashLead = 4;

    private static DashRun Measure(MatchContentEntry entry, float distance, TargetMove move, byte followUp,
        bool attackerJumps = false, bool apex = false, bool midDash = false, bool doubleJump = false)
    {
        var def = entry.Definition;
        var sim = new ServerSimulation(Program.BuildArena());
        float ground = def.CapsuleHeight * 0.5f;
        sim.RegisterEntity(Attacker, def, Fighter(Attacker, ground, StartX, StartZ, 0f, def), entry.BakedAnimation);
        sim.RegisterEntity(Defender, def, Fighter(Defender, ground, StartX, StartZ + distance, MathF.PI, def), entry.BakedAnimation);
        Step(sim, default, default);
        if (attackerJumps)
        {
            bool second = false;
            for (int t = 0, since = 0; t < (apex ? 200 : JumpLead); t++, since++)
            {
                bool press = t == 0 || second && since == 0;
                Step(sim, new InputState { Jump = press, JumpHeld = true }, default);
                var rising = sim.GetState(Attacker);
                if (!apex || since <= 4 || rising.IsGrounded || rising.VY > 0f) continue;
                if (!doubleJump || second) break;
                second = true;
                since = -1;
            }
        }

        int arrive = -1, miss = -1, actionable = -1, contact = -1;
        float arrivalY = 0f, contactY = 0f, arrivalDy = 0f;
        bool pressed = false;
        for (int t = 0; t < 240; t++)
        {
            var attackerInput = t == 0 ? new InputState { DashPressed = true } : default;
            var state = sim.GetState(Attacker);
            if (followUp != 0 && !pressed && (midDash ? t == HomingDashConfig.FloatTicks + MidDashLead : arrive >= 0))
            {
                attackerInput.ActiveSlot = followUp;
                pressed = true;
            }
            var defenderInput = move switch
            {
                TargetMove.Jump => new InputState { Jump = t == 0, JumpHeld = t < 12 },
                TargetMove.Sidestep => new InputState { MoveX = 1f, Right = true },
                _ => default,
            };
            Step(sim, attackerInput, defenderInput);
            state = sim.GetState(Attacker);
            if (arrive < 0 && state.State == ActionState.HomingDashArrive) { arrive = t; arrivalY = state.PY - ground; arrivalDy = state.PY - sim.GetState(Defender).PY; }
            if (miss < 0 && state.State == ActionState.HomingDashMiss) miss = t;
            if (contact < 0 && sim.LastTickHits.Any(h => h.OwnerEntityId == Attacker && h.TargetEntityId == Defender))
            {
                contact = t;
                contactY = state.PY - ground;
            }
            if (actionable < 0 && t > 0 && (arrive >= 0 || miss >= 0) && state.State is ActionState.Idle or ActionState.Run
                && state.AnimLockTicks == 0)
                actionable = t;
            if (followUp == 0 ? actionable >= 0 : contact >= 0 || (pressed && arrive >= 0 && t > arrive + 90)) break;
        }
        return new DashRun(arrive, miss, actionable, contact, arrivalY, contact >= 0 ? arrivalY - contactY : 0f, arrivalDy);
    }

    private static int StandingHit(MatchContentEntry entry, float spacing, byte slot)
    {
        var def = entry.Definition;
        var sim = new ServerSimulation(Program.BuildArena());
        float ground = def.CapsuleHeight * 0.5f;
        sim.RegisterEntity(Attacker, def, Fighter(Attacker, ground, StartX, StartZ, 0f, def), entry.BakedAnimation);
        sim.RegisterEntity(Defender, def, Fighter(Defender, ground, StartX, StartZ + spacing, MathF.PI, def), entry.BakedAnimation);
        Step(sim, default, default);
        for (int t = 0; t < 90; t++)
        {
            Step(sim, t == 0 ? new InputState { ActiveSlot = slot } : default, default);
            if (sim.LastTickHits.Any(h => h.OwnerEntityId == Attacker && h.TargetEntityId == Defender)) return t;
        }
        return -1;
    }

    private static CharacterState Fighter(ulong id, float ground, float x, float z, float yaw, CharacterDefinition def) => new()
    {
        EntityId = id, PX = x, PY = ground, PZ = z, FacingYaw = yaw, IsGrounded = true,
        State = ActionState.Idle, JumpsLeft = (byte)def.Movement.MaxJumps, AirDodgesLeft = 1,
    };

    private static void Step(ServerSimulation sim, InputState attacker, InputState defender)
        => sim.Tick(new Dictionary<ulong, InputState> { [Attacker] = attacker, [Defender] = defender });

    private static string Ticks(int arrive, int miss) => arrive >= 0 ? $"{arrive}" : miss >= 0 ? $"miss {miss}" : "?";

    private static string Hit(int tick) => tick >= 0 ? tick.ToString() : "-";
}
