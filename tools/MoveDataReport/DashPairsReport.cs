using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using SlopArena.Shared;

namespace SlopArena.MoveDataReport;

/// <summary>
/// Beeline into normals for every attacker × defender pair: does a grounded Beeline give a ground
/// normal that connects, and an airborne Beeline an aerial that connects?
/// Usage: dotnet run --project tools/MoveDataReport -- --dash-pairs [--out path] [--csv path]
/// </summary>
internal static class DashPairsReport
{
    private const ulong Attacker = 1, Defender = 100;
    private const float StartX = 50f, StartZ = 50f;
    private const int PressLead = 4;
    private static readonly float[] Distances = { 3f, 6f, 9f, 12f };
    private static readonly (string Name, CharacterClass Class)[] Roster =
    {
        ("FightGuy", CharacterClass.FightGuy), ("Wibou", CharacterClass.Wibou), ("Manki", CharacterClass.Manki),
        ("Sir Bonk", CharacterClass.Bonk), ("Bashie", CharacterClass.Bashie), ("Salamander", CharacterClass.Salamander),
    };
    private static readonly (string Label, byte Wire)[] Normals =
        { ("1", AbilitySlots.Normal1), ("2", AbilitySlots.Normal2), ("3", AbilitySlots.Normal3) };

    private enum Start { Ground, Rising, Apex }

    private sealed record Scenario(string Key, string Label, Start Start, bool TargetJumps, bool WantsGround);

    private static readonly Scenario[] Scenarios =
    {
        new("ground", "Grounded Beeline, target standing", Start.Ground, false, true),
        new("ground-vs-jump", "Grounded Beeline, target jumps on the press", Start.Ground, true, true),
        new("rising", "Jump, Beeline 10 t later, target standing", Start.Rising, false, false),
        new("apex", "Beeline at the jump apex, target standing", Start.Apex, false, false),
        new("apex-vs-jump", "Beeline at the jump apex, target jumps on the press", Start.Apex, true, false),
    };

    private sealed record DashRun(int Arrive, float Gap, char CameOut, int Contact);

    internal static int Run(string[] args)
    {
        string? outPath = Program.ParseArg(args, "--out");
        string? csvPath = Program.ParseArg(args, "--csv");
        var fighters = Roster.Select(r => (r.Name, Entry: BuiltInContentResolver.Resolve(r.Class))).ToArray();
        var md = new StringBuilder();
        var csv = new StringBuilder("scenario,attacker,defender,distance,normal,arrive,gap,came_out,contact\n");
        int runs = fighters.Length * Distances.Length;
        md.AppendLine("# Beeline into normals, every pair");
        md.AppendLine();
        md.AppendLine($"> Generated by `tools/MoveDataReport --dash-pairs` ({DateTime.UtcNow:yyyy-MM-dd HH:mm} UTC) from the real shared sim on flat ground. " +
            $"The normal is pressed {PressLead} t into the travel and held for the arrival. Each cell is hits out of {runs} runs " +
            $"({fighters.Length} defenders × {string.Join(", ", Distances.Select(d => $"{d:0}"))} m). " +
            "A run counts only when the expected version came out: the ground normal after a grounded Beeline, the aerial after an airborne one. " +
            "**wrong** = runs where the other version came out.");
        foreach (var sc in Scenarios)
        {
            md.AppendLine();
            md.AppendLine($"## {sc.Label}");
            md.AppendLine();
            md.AppendLine("| attacker | 1 | 2 | 3 | wrong | horizontal gap on arrival |");
            md.AppendLine("|---|---:|---:|---:|---:|---|");
            foreach (var att in fighters)
            {
                var cells = new List<string>();
                int wrong = 0;
                var gaps = new List<float>();
                foreach (var n in Normals)
                {
                    int hits = 0;
                    foreach (var def in fighters)
                    foreach (float d in Distances)
                    {
                        var r = Measure(att.Entry, def.Entry, d, sc.Start, sc.TargetJumps, n.Wire);
                        char expected = sc.WantsGround ? 'g' : 'a';
                        if (r.CameOut != '-' && r.CameOut != expected) wrong++;
                        if (r.Contact >= 0 && r.CameOut == expected) hits++;
                        if (r.Arrive >= 0) gaps.Add(r.Gap);
                        csv.AppendLine($"{sc.Key},{att.Name},{def.Name},{d},{n.Label},{r.Arrive},{r.Gap:0.000},{r.CameOut},{r.Contact}");
                    }
                    cells.Add($"{hits}/{runs}");
                }
                string gap = gaps.Count == 0 ? "-" : $"{gaps.Min():0.00}–{gaps.Max():0.00} m";
                md.AppendLine($"| {att.Name} | {string.Join(" | ", cells)} | {wrong} | {gap} |");
            }
        }
        Write(outPath, md.ToString());
        if (csvPath != null) Write(csvPath, csv.ToString());
        return 0;
    }

    private static void Write(string? path, string text)
    {
        if (path == null) { Console.Write(text); return; }
        string? dir = Path.GetDirectoryName(path);
        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
        File.WriteAllText(path, text);
        Console.Error.WriteLine($"wrote {path}");
    }

    private static DashRun Measure(MatchContentEntry attacker, MatchContentEntry defender, float distance, Start start,
        bool targetJumps, byte slot)
    {
        var sim = new ServerSimulation(Program.BuildArena());
        var a = attacker.Definition;
        var b = defender.Definition;
        sim.RegisterEntity(Attacker, a, Fighter(Attacker, a, StartX, StartZ, 0f), attacker.BakedAnimation);
        sim.RegisterEntity(Defender, b, Fighter(Defender, b, StartX, StartZ + distance, MathF.PI), defender.BakedAnimation);
        Step(sim, default, default);
        if (start != Start.Ground)
        {
            for (int t = 0; t < 200; t++)
            {
                Step(sim, new InputState { Jump = t == 0, JumpHeld = true }, default);
                var rising = sim.GetState(Attacker);
                if (start == Start.Rising && t == 9) break;
                if (start == Start.Apex && t > 4 && !rising.IsGrounded && rising.VY <= 0f) break;
            }
        }

        int arrive = -1, contact = -1;
        float gap = 0f;
        char cameOut = '-';
        for (int t = 0; t < 200; t++)
        {
            var input = t == 0 ? new InputState { DashPressed = true } : default;
            if (t == HomingDashConfig.FloatTicks + PressLead) input.ActiveSlot = slot;
            var defenderInput = targetJumps ? new InputState { Jump = t == 0, JumpHeld = t < 12 } : default;
            Step(sim, input, defenderInput);
            var s = sim.GetState(Attacker);
            if (arrive < 0 && s.State == ActionState.HomingDashArrive)
            {
                arrive = t;
                var o = sim.GetState(Defender);
                float dx = o.PX - s.PX, dz = o.PZ - s.PZ;
                gap = MathF.Sqrt(dx * dx + dz * dz) - a.CapsuleRadius - b.CapsuleRadius;
            }
            if (s.State == ActionState.HomingDashMiss) break;
            if (cameOut == '-' && s.AttackSlot != 0) cameOut = s.IsGrounded ? 'g' : 'a';
            if (sim.LastTickHits.Any(h => h.OwnerEntityId == Attacker && h.TargetEntityId == Defender)) { contact = t; break; }
            if (arrive >= 0 && t > arrive + 90) break;
        }
        return new DashRun(arrive, gap, cameOut, contact);
    }

    private static CharacterState Fighter(ulong id, CharacterDefinition def, float x, float z, float yaw) => new()
    {
        EntityId = id, PX = x, PY = def.CapsuleHeight * 0.5f, PZ = z, FacingYaw = yaw, IsGrounded = true,
        State = ActionState.Idle, JumpsLeft = (byte)def.Movement.MaxJumps, AirDodgesLeft = 1,
    };

    private static void Step(ServerSimulation sim, InputState attacker, InputState defender)
        => sim.Tick(new Dictionary<ulong, InputState> { [Attacker] = attacker, [Defender] = defender });
}
