using System.Reflection;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using SlopArena.Shared;

namespace SlopArena.KitCheck;

public static class AuthoringReference
{
    public const string Start = "<!-- BEGIN GENERATED CONTRACT -->";
    public const string End = "<!-- END GENERATED CONTRACT -->";

    public static string Generate(string root)
    {
        var codec = Parse(root, "CharacterPackageSourceCodec.cs");
        var compiler = Parse(root, "CharacterPackageCompiler.cs");
        var text = new StringBuilder(Start + "\n\n## Generated contract\n\n");
        text.AppendLine("Generated by `dotnet run --project tools/KitCheck -p:SkipUnityPluginCopy=true -- reference --write .`. Do not edit this section.\n");
        text.AppendLine("### Canonical move grid\n");
        text.AppendLine(string.Join(", ", CharacterPackageCompiler.CanonicalSlotIds.Select(x => "`" + x + "`")) + ".\n");
        text.AppendLine("### Public capabilities\n");
        text.AppendLine("Declare each used capability in `capabilityRequirements`. Its ID and version must also match the `startCapability` operation. Forms and shell stance also govern document-level data.\n");
        text.AppendLine("| ID | Version |\n| --- | --- |");
        foreach (var field in typeof(CharacterPackageCompiler).GetFields(BindingFlags.Public | BindingFlags.Static).Where(f => f.Name.EndsWith("CapabilityId", StringComparison.Ordinal)))
        {
            var version = typeof(CharacterPackageCompiler).GetField(field.Name[..^2] + "Version")!;
            text.AppendLine($"| `{field.GetRawConstantValue()}` | `{version.GetRawConstantValue()}` |");
        }
        text.AppendLine("\n### Budgets\n\nEvery operation consumes one operation entry, including completion and presentation. Aliases expand before counting slots and stages. Nested capability hitboxes and projectiles count through their capability's cooking rules.\n");
        text.AppendLine("| Limit | Value |\n| --- | --- |");
        foreach (var field in typeof(CookedBudget).GetFields(BindingFlags.Public | BindingFlags.Static).Where(x => x.IsLiteral))
            text.AppendLine($"| {field.Name} | {field.GetRawConstantValue()} |");
        text.AppendLine("\n### Source objects and fields\n\nEach table lists the accepted keys for an object. Objects and arrays are required unless the table says otherwise. `null` is distinct from an omitted key. Optional strings accept null. Required fields have no default.\n");
        text.AppendLine("Numbers use finite 32-bit floating point. Unsigned 16-bit integers are 0 through 65535. Bytes are 0 through 255. Further constraints appear below. A default shown as an enum name uses the corresponding JSON token in the enum table.\n");
        foreach (var method in codec.DescendantNodes().OfType<MethodDeclarationSyntax>().Where(x => x.Identifier.Text.StartsWith("Parse", StringComparison.Ordinal) && x.Identifier.Text != "ParseOperations"))
        {
            var objects = Calls(method).Where(x => Name(x) is "Object" or "ReadObject" or "ReadObjectWithCode").ToArray();
            foreach (var obj in objects)
            {
                var args = obj.ArgumentList.Arguments;
                var offset = Name(obj) is "Object" or "ReadObjectWithCode" ? 4 : 3;
                var keys = args.Skip(offset).SelectMany(x => ResolveStrings(x.Expression, codec)).ToArray();
                if (keys.Length == 0) continue;
                var label = args[1].ToString();
                text.AppendLine($"#### {method.Identifier.Text[5..]} object {Escape(label)}\n");
                Fields(text, keys, method);
            }
        }
        text.AppendLine("### Operation kinds\n\nThe common fields are `kind` (string), `tick` (stage-relative unsigned 16-bit integer), and `unit` (string). Each is required. Same-tick operations run in array order. A tick must be inside its stage.\n");
        var operationFields = codec.DescendantNodes().OfType<MethodDeclarationSyntax>().Single(x => x.Identifier.Text == "ValidateOperationFields");
        foreach (var arm in operationFields.DescendantNodes().OfType<SwitchExpressionArmSyntax>())
        {
            var kind = arm.Pattern.DescendantNodesAndSelf().OfType<LiteralExpressionSyntax>().FirstOrDefault()?.Token.ValueText;
            if (kind == null) continue;
            text.AppendLine($"#### `{kind}`\n");

            var parseOps = codec.DescendantNodes().OfType<MethodDeclarationSyntax>().Single(x => x.Identifier.Text == "ParseOperations");
            var section = parseOps.DescendantNodes().OfType<SwitchSectionSyntax>().First(x => x.Labels.Any(l => l.ToString().Contains("\"" + kind + "\"")));
            var sourceType = section.DescendantNodes().OfType<ObjectCreationExpressionSyntax>().First().Type.ToString();
            var unitSwitch = compiler.DescendantNodes().OfType<MethodDeclarationSyntax>().Single(x => x.Identifier.Text == "ValidateOperation")
                .DescendantNodes().OfType<SwitchExpressionSyntax>().First();
            var unitArm = unitSwitch.Arms.FirstOrDefault(x => x.Pattern.ToString().Contains(sourceType, StringComparison.Ordinal)) ?? unitSwitch.Arms.Last();
            var enumName = unitArm.Expression.ToString().Split('.').Last();
            var unit = char.ToLowerInvariant(enumName[0]) + enumName[1..];
            text.AppendLine($"Unit is `{unit}`. Budget cost is one operation entry.\n");
            Fields(text, Strings(arm.Expression).Where(x => x is not ("kind" or "tick" or "unit")), section);
        }
        text.AppendLine("### Capability parameter objects\n");
        var parameters = codec.DescendantNodes().OfType<MethodDeclarationSyntax>().Single(x => x.Identifier.Text == "ParseCapabilityParameters");
        foreach (var arm in parameters.DescendantNodes().OfType<SwitchExpressionArmSyntax>())
        {
            var id = Literal((arm.Pattern as ConstantPatternSyntax)?.Expression);
            if (id == null && arm.Pattern is ConstantPatternSyntax cp && cp.Expression is MemberAccessExpressionSyntax member)
                id = typeof(CharacterPackageCompiler).GetField(member.Name.ToString())?.GetRawConstantValue()?.ToString();
            if (id == null || !id.StartsWith("slop.ability.", StringComparison.Ordinal)) continue;
            text.AppendLine($"#### `{id}` parameters\n");
            var expression = arm.Expression;
            if (expression is IdentifierNameSyntax identifier)
                expression = codec.DescendantNodes().OfType<VariableDeclaratorSyntax>().Single(x => x.Identifier.Text == identifier.Identifier.Text).Initializer!.Value;
            var constantName = typeof(CharacterPackageCompiler).GetFields(BindingFlags.Public | BindingFlags.Static)
                .First(x => x.IsLiteral && Equals(x.GetRawConstantValue(), id)).Name;
            var branch = parameters.DescendantNodes().OfType<IfStatementSyntax>()
                .FirstOrDefault(x => x.Condition.ToString() == "id == CharacterPackageCompiler." + constantName);
            SyntaxNode parameterScope = branch?.Statement ?? (SyntaxNode)parameters;
            var helperCall = branch?.Statement.DescendantNodesAndSelf().OfType<InvocationExpressionSyntax>()
                .FirstOrDefault(x => Name(x).StartsWith("Parse", StringComparison.Ordinal));
            if (helperCall != null && Name(helperCall) is not ("ParseHitboxNamed" or "ParseProjectile" or "ParseHitbox"))
                parameterScope = codec.DescendantNodes().OfType<MethodDeclarationSyntax>().First(x => x.Identifier.Text == Name(helperCall));
            Fields(text, ResolveStrings(expression, codec), parameterScope);
        }
        var parameterIds = parameters.DescendantNodes().OfType<SwitchExpressionArmSyntax>().Select(x => x.Pattern.ToString()).ToArray();
        foreach (var field in typeof(CharacterPackageCompiler).GetFields(BindingFlags.Public | BindingFlags.Static).Where(x => x.Name.EndsWith("CapabilityId", StringComparison.Ordinal)))
            if (!parameterIds.Any(x => x.Contains(field.GetRawConstantValue()!.ToString()!, StringComparison.Ordinal) || x.EndsWith("." + field.Name, StringComparison.Ordinal)))
                text.AppendLine($"`{field.GetRawConstantValue()}` has no supported `startCapability` parameter object. It declares a document-level feature.\n");
        text.AppendLine("### Enum tokens\n\n| Enum | Allowed strings |\n| --- | --- |");
        foreach (var method in codec.DescendantNodes().OfType<MethodDeclarationSyntax>().Where(x => x.ExpressionBody != null && x.Identifier.Text.StartsWith("Parse", StringComparison.Ordinal)))
            text.AppendLine($"| {method.Identifier.Text[5..]} | {string.Join(", ", method.DescendantNodes().OfType<SwitchExpressionArmSyntax>().Select(x => Literal((x.Pattern as ConstantPatternSyntax)?.Expression)).Where(x => x != null).Select(x => "`" + x + "`"))} |");
        text.AppendLine("\n### Bone identifiers\n");
        var bones = File.ReadAllText(Path.Combine(root, "src/Shared/CharacterBoneRegistry.cs"));
        text.AppendLine(string.Join(", ", System.Text.RegularExpressions.Regex.Matches(bones, "\"(bone\\.[^\"]+)\"").Select(x => x.Groups[1].Value).Distinct().Select(x => "`" + x + "`")) + ".\n");
        text.AppendLine("### Validation rules and diagnostics\n\nThese rules come directly from validation statements. The condition is the rejected case. `&&` means both, `||` means either, `!` means not, and `x is > a and <= b` means a < x ≤ b. Names with capital letters refer to the matching camelCase JSON fields. Index variables mean the current array entry. Helper predicates below state their accepted case.\n");
        text.AppendLine("| Code | Rejected condition or context | Message |\n| --- | --- | --- |");
        var contracts = Directory.GetFiles(Path.Combine(root, "src/Shared"), "*.cs", SearchOption.AllDirectories)
            .OrderBy(x => x, StringComparer.Ordinal).Select(File.ReadAllText)
            .Where(x => x.Contains("Contract", StringComparison.Ordinal))
            .SelectMany(x => CSharpSyntaxTree.ParseText(x).GetRoot().DescendantNodes().OfType<ClassDeclarationSyntax>())
            .Where(x => x.Identifier.Text.EndsWith("Contract", StringComparison.Ordinal)).Cast<SyntaxNode>().ToArray();
        var sources = new[] { codec, compiler }.Concat(contracts).ToArray();
        foreach (var source in sources)
        foreach (var call in Calls(source).Where(x => Name(x) is "Error" or "Warning"))
        {
            var args = call.ArgumentList.Arguments;
            if (args.Count < 3) continue;
            var condition = call.Ancestors().OfType<IfStatementSyntax>().FirstOrDefault()?.Condition.ToString()
                ?? call.Ancestors().OfType<SwitchSectionSyntax>().FirstOrDefault()?.Labels.ToString()
                ?? call.Ancestors().OfType<MethodDeclarationSyntax>().FirstOrDefault()?.Identifier.Text ?? "";
            text.AppendLine($"| `{Escape(args[0].ToString())}` | `{Escape(condition)}` | {Escape(Literal(args[2].Expression) ?? args[2].ToString())} |");
        }
        text.AppendLine("\n### Accepted bounds predicates\n\nThese expressions are the compiler's shared predicates. All terms must hold. They supply the exact coupled limits for the diagnostics above.\n");
        foreach (var method in sources.SelectMany(x => x.DescendantNodes().OfType<MethodDeclarationSyntax>()).Where(x => x.ExpressionBody != null && (x.Identifier.Text.StartsWith("Valid", StringComparison.Ordinal) || x.ReturnType.ToString() == "string?")))
            text.AppendLine($"- `{Escape(method.Identifier.Text)}({Escape(string.Join(", ", method.ParameterList.Parameters.Select(x => x.Identifier.Text)))})` accepts `{Escape(method.ExpressionBody!.Expression.ToString())}`.\n");
        text.AppendLine("### Validation constants\n\n| Name | Value |\n| --- | --- |");
        foreach (var declaration in compiler.DescendantNodes().OfType<FieldDeclarationSyntax>().Where(x => x.Modifiers.Any(SyntaxKind.ConstKeyword)))
            foreach (var variable in declaration.Declaration.Variables)
                text.AppendLine($"| `{variable.Identifier.Text}` | `{Escape(variable.Initializer!.Value.ToString())}` |");
        text.AppendLine("\n### Bounds returned by helper rules\n\n| Rule | Rejected condition | Message |\n| --- | --- | --- |");
        foreach (var method in sources.SelectMany(x => x.DescendantNodes().OfType<MethodDeclarationSyntax>()).Where(x => x.ReturnType.ToString() == "string?"))
            foreach (var statement in method.DescendantNodes().OfType<ReturnStatementSyntax>().Where(x => x.Expression != null && !x.Expression.IsKind(SyntaxKind.NullLiteralExpression)))
                text.AppendLine($"| `{method.Identifier.Text}` | `{Escape(statement.Ancestors().OfType<IfStatementSyntax>().FirstOrDefault()?.Condition.ToString() ?? "see expression")}` | {Escape(Literal(statement.Expression) ?? statement.Expression!.ToString())} |");
        text.AppendLine("\n### Retired capability IDs\n\nThese produce `capability.retired`.\n\n| ID | Reason |\n| --- | --- |");
        var retired = Parse(root, "RetiredCapabilities.cs");
        foreach (var assignment in retired.DescendantNodes().OfType<AssignmentExpressionSyntax>())
        {
            var id = Strings(assignment.Left).FirstOrDefault();
            if (id != null && Literal(assignment.Right) is { } reason) text.AppendLine($"| `{id}` | {Escape(reason)} |");
        }
        text.AppendLine("\n### Budget accounting rules\n\n| Counter | Increment | Condition |\n| --- | --- | --- |");
        var cook = compiler.DescendantNodes().OfType<MethodDeclarationSyntax>().Single(x => x.Identifier.Text == "CookTimeline");
        foreach (var expression in cook.DescendantNodes().OfType<ExpressionStatementSyntax>().Where(x =>
            x.Expression is PostfixUnaryExpressionSyntax || x.Expression is AssignmentExpressionSyntax a && a.IsKind(SyntaxKind.AddAssignmentExpression)))
        {
            var value = expression.Expression;
            var counter = value is PostfixUnaryExpressionSyntax post ? post.Operand.ToString() : ((AssignmentExpressionSyntax)value).Left.ToString();
            if (counter is not ("operations" or "timelineOperations" or "hitboxes" or "projectiles" or "capabilities")) continue;
            var amount = value is PostfixUnaryExpressionSyntax ? "1" : ((AssignmentExpressionSyntax)value).Right.ToString();
            var context = expression.Ancestors().OfType<IfStatementSyntax>().FirstOrDefault()?.Condition.ToString()
                ?? expression.Ancestors().OfType<SwitchSectionSyntax>().FirstOrDefault()?.Labels.ToString() ?? "each authored operation";
            text.AppendLine($"| {counter} | {amount} | `{Escape(context)}` |");
        }
        text.AppendLine(End);
        return text.ToString().Replace("\r\n", "\n");
    }

    private static IEnumerable<InvocationExpressionSyntax> ReaderCalls(SyntaxNode scope)
    {
        var visited = new HashSet<string>(StringComparer.Ordinal);
        var pending = new Queue<SyntaxNode>();
        pending.Enqueue(scope);
        while (pending.Count > 0)
        {
            var node = pending.Dequeue();
            foreach (var call in Calls(node))
            {
                yield return call;
                var name = Name(call);
                if (!name.StartsWith("Parse", StringComparison.Ordinal) || !visited.Add(name)) continue;
                var helper = scope.SyntaxTree.GetRoot().DescendantNodes().OfType<MethodDeclarationSyntax>().FirstOrDefault(x => x.Identifier.Text == name);
                if (helper != null) pending.Enqueue(helper);
            }
        }
    }

    private static IEnumerable<string> ResolveStrings(SyntaxNode node, SyntaxNode codec)
    {
        if (node is IdentifierNameSyntax identifier)
        {
            var declaration = codec.DescendantNodes().OfType<VariableDeclaratorSyntax>().FirstOrDefault(x => x.Identifier.Text == identifier.Identifier.Text && x.Initializer != null);
            if (declaration?.Initializer != null)
            {
                if (declaration.Initializer.Value.ToString().Contains("new FormPresentation()", StringComparison.Ordinal))
                    return new FormPresentation().Roles.Select(x => x.Name);
                return ResolveStrings(declaration.Initializer.Value, codec);
            }
            return Enumerable.Empty<string>();
        }
        if (node is LiteralExpressionSyntax literal) return literal.IsKind(SyntaxKind.StringLiteralExpression) ? new[] { literal.Token.ValueText } : Enumerable.Empty<string>();
        return node.ChildNodes().SelectMany(x => ResolveStrings(x, codec));
    }

    private static SyntaxNode Parse(string root, string file) => CSharpSyntaxTree.ParseText(File.ReadAllText(Path.Combine(root, "src/Shared", file))).GetRoot();
    private static IEnumerable<InvocationExpressionSyntax> Calls(SyntaxNode node) => node.DescendantNodes().OfType<InvocationExpressionSyntax>();
    private static string Name(InvocationExpressionSyntax call) => call.Expression is MemberAccessExpressionSyntax m ? m.Name.ToString() : call.Expression.ToString();
    private static string? Literal(ExpressionSyntax? node) => node is LiteralExpressionSyntax l && l.IsKind(SyntaxKind.StringLiteralExpression) ? l.Token.ValueText : null;
    private static IEnumerable<string> Strings(SyntaxNode node) => node.DescendantNodes().OfType<LiteralExpressionSyntax>().Where(x => x.IsKind(SyntaxKind.StringLiteralExpression)).Select(x => x.Token.ValueText);
    private static string Escape(string value) => value.Replace("|", "&#124;").Replace("\r", "").Replace("\n", " ");

    private static void Fields(StringBuilder text, IEnumerable<string> fields, SyntaxNode scope)
    {
        text.AppendLine("| Field | Type | Omission/default |\n| --- | --- | --- |");
        foreach (var field in fields.Distinct())
        {
            var read = ReaderCalls(scope).FirstOrDefault(x => x.ArgumentList.Arguments.Count >= 2 && Literal(x.ArgumentList.Arguments[1].Expression) == field &&
                Name(x) is "Float" or "OptionalFloat" or "OptionalFloatOrDefault" or "UShort" or "OptionalUShort" or "Byte" or "String" or "OptionalString" or "Bool" or "OptionalBool" or "EnumValue" or "OptionalEnumValue" or "ParseStringArray" or "Array");
            var kind = read == null ? "object; see matching object table" : Name(read);
            var role = Calls(scope).FirstOrDefault(x => x.ArgumentList.Arguments.Count == 1 && Literal(x.ArgumentList.Arguments[0].Expression) == field && scope.DescendantNodes().OfType<LocalFunctionStatementSyntax>().Any(f => f.Identifier.Text == Name(x)));
            if (role != null) kind = "OptionalString";
            var wholeCodec = scope.SyntaxTree.GetRoot();
            if (read == null && Calls(wholeCodec).Any(x => Name(x) == "Array" && x.ArgumentList.Arguments.Count > 1 && Literal(x.ArgumentList.Arguments[1].Expression) == field)) kind = "Array";
            if (read == null && Calls(scope).Any(x => Name(x) == "TryGetInt32") && field == "maxCharges") kind = "signed 32-bit integer";
            if (read == null && Calls(scope).Any(x => Name(x) == "Array" && x.ArgumentList.Arguments.Any(a => Literal(a.Expression) == field))) kind = "Array";
            var arrayGuard = Calls(scope).FirstOrDefault(x => Name(x) == "TryGetValue" && x.ArgumentList.Arguments.Any(a => Literal(a.Expression) == field));
            var variable = arrayGuard?.ArgumentList.Arguments.Select(a => a.Expression).OfType<DeclarationExpressionSyntax>().FirstOrDefault()?.Designation.ToString();
            if (read == null && variable != null && scope.ToString().Contains(variable + ".ValueKind != JsonValueKind.Array", StringComparison.Ordinal)) kind = "Array";
            var type = kind.Contains("Float") ? "number" : kind.Contains("UShort") ? "unsigned 16-bit integer" : kind == "Byte" ? "byte" : kind.Contains("Bool") ? "boolean" : kind.Contains("Enum") ? "enum string" : kind.Contains("StringArray") ? "string array" : kind == "Array" ? "array" : kind.Contains("String") ? "string" : kind;
            var fallback = kind.StartsWith("Optional", StringComparison.Ordinal) ? kind switch
            {
                "OptionalString" => role != null ? "\"\"" : "null (some roles normalize to empty string)",
                "OptionalFloat" => "0",
                "OptionalBool" => "false",
                _ => read!.ArgumentList.Arguments.Last().ToString()
            } : "required";
            var conditional = read?.Ancestors().OfType<ConditionalExpressionSyntax>().FirstOrDefault();
            if (conditional != null) fallback = conditional.WhenFalse.ToString();
            if (read?.Parent is BinaryExpressionSyntax coalesce && coalesce.IsKind(SyntaxKind.CoalesceExpression)) fallback = coalesce.Right.ToString();
            if (kind.StartsWith("object", StringComparison.Ordinal))
            {
                var guard = Calls(scope).FirstOrDefault(x => Name(x) is "ContainsKey" or "TryGetValue" && x.ArgumentList.Arguments.Any(a => Literal(a.Expression) == field));
                var optional = guard?.Ancestors().OfType<ConditionalExpressionSyntax>().FirstOrDefault();
                if (optional != null) fallback = optional.WhenFalse.ToString();
                else if (guard != null && !Calls(scope).Any(x => Name(x) == "Error" && x.ArgumentList.Arguments.Any(a => a.ToString().Contains("." + field + "\"", StringComparison.Ordinal)))) fallback = "omitted";
                var helper = wholeCodec.DescendantNodes().OfType<MethodDeclarationSyntax>().FirstOrDefault(m =>
                    m.Identifier.Text.StartsWith("Parse", StringComparison.Ordinal) && Calls(m).Any(x => Name(x) == "TryGetValue" && x.ArgumentList.Arguments.Any(a => Literal(a.Expression) == field)) &&
                    m.DescendantNodes().OfType<ReturnStatementSyntax>().Any(r => r.Expression?.IsKind(SyntaxKind.NullLiteralExpression) == true));
                if (helper != null) fallback = "null";
            }
            if (field is "schemaVersion" or "class" || field == "id" && scope is MethodDeclarationSyntax m && m.Identifier.Text is "ParseManifest" or "ParseCharacter") fallback = "forbidden; see diagnostics";
            text.AppendLine($"| `{field}` | {type} | {Escape(fallback)} |");
        }
        text.AppendLine();
    }
}
